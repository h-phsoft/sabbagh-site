        <h2>About Sabbagh Est.</h2>
        <p>Sabbagh Est. was founded in 1949 by Edmond Sabbagh and specializes in the manufacturing of beauty and personal care products.</p>
        <p>From 1949 to 2007, Sabbagh Est. was the exclusive manufacturer and distributor of L’Oréal Paris in Syria, producing a wide portfolio of globally recognized brands. These included Garnier ranges such as Imedia and Belle Color hair coloration, Ultra Doux hair care, Ambre Solaire sun care, and Synergie skin care. The company also manufactured L’Oréal products including Elseve hair care, Recital, Excellence, and Préférence hair coloration, as well as Majirel professional color and Platifiz bleaching powder.</p>
        <p>Expanding its industrial capabilities, Sabbagh Est. established a second factory specialized in aerosol production, primarily focused on insecticides. Between 1993 and 2003, the company was the exclusive licensed producer of “Pif Paf”, one of the leading insecticide brands by Reckitt Benckiser in the Syrian market. This facility also supported the production of aerosol-based personal care products such as Garnier Obao deodorant, L’Oréal Printil deodorant, and L’Oréal Elnett professional hairspray.</p>
        <p>Today, Sabbagh Est. manufactures a broad range of products, including shampoos and conditioners, hair colorations, liquid soaps, shower gels, creams and lotions, antiseptics and sanitizers, bleaching powders, nail polish removers, and body sprays.</p>
        <p>In addition to its own brands, the company offers private label manufacturing.</p>

